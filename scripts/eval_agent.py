"""Evaluate the agent's judgment step (Claude) against hand labels. Writes docs/EVALUATION.md.

Input: the captured live London feed (113 real records) + 8 synthetic replay records.
Scored decision: is the record "actionable", i.e. does the pipeline get an explicit, verified,
non-superseded pedestrian statement from it? That is the decision that can change a route.

Costs real API tokens (about 250k input tokens). Run:  python scripts/eval_agent.py
"""
from __future__ import annotations

import json
import statistics
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from lantern import tfl  # noqa: E402
from lantern.agent.assess import MODEL, claude_assessor, verify_assessment  # noqa: E402
from lantern.agent.replay import replay_records  # noqa: E402
from lantern.config import DATA_FIXTURES, ROOT  # noqa: E402
from lantern.env import load_env  # noqa: E402

PRICE_IN, PRICE_OUT = 4.00, 20.00   # USD per million tokens, claude-opus-5-5 list price


def actionable(ev: dict, a: dict) -> bool:
    return (a["pedestrian_impact"] in ("footway_closed", "footway_restricted", "crossing_affected")
            and a["basis"] == "explicit" and not a["superseded_or_cleared"]
            and not verify_assessment(ev, a))


def main() -> int:
    load_env()
    now = datetime.now(timezone.utc)
    recs, meta = replay_records(now, "1", include_capture=True)
    labels = json.loads((DATA_FIXTURES / "eval_labels.json").read_text(encoding="utf-8"))["labels"]
    events = [tfl.normalise(r)[0] for r in recs]
    events = [e for e in events if e]
    assess = claude_assessor()

    def one(ev):
        t = time.time()
        try:
            a = assess(ev)
            return ev, a, time.time() - t, None
        except Exception as exc:  # noqa: BLE001
            return ev, None, time.time() - t, f"{type(exc).__name__}: {exc}"

    t0 = time.time()
    with ThreadPoolExecutor(max_workers=8) as pool:
        results = list(pool.map(one, events))
    wall = time.time() - t0

    # Second pass on the labelled subset to measure run-to-run agreement.
    subset = [ev for ev in events if ev["id"] in labels]
    with ThreadPoolExecutor(max_workers=8) as pool:
        second = {ev["id"]: a for ev, a, _, err in pool.map(one, subset) if a}

    tp = fp = fn = tn = 0
    errors, rows, failures = [], [], []
    quotes_checked = quotes_ok = 0
    impact_ok = impact_n = 0
    tok_in = tok_out = 0
    lat = []
    agree = agree_n = 0
    for ev, a, dt, err in results:
        if err:
            failures.append((ev["id"], err))
            continue
        lat.append(dt)
        tok_in += a["_usage"]["input_tokens"]
        tok_out += a["_usage"]["output_tokens"]
        lab = labels.get(ev["id"], {"actionable": False, "impact": ["none"], "note": "keyword screen: no pedestrian statement"})
        pred = actionable(ev, a)
        if a["pedestrian_impact"] in ("footway_closed", "footway_restricted", "crossing_affected"):
            quotes_checked += 1
            quotes_ok += not verify_assessment(ev, a)
        if ev["id"] in labels:
            impact_n += 1
            impact_ok += a["pedestrian_impact"] in lab["impact"]
            if ev["id"] in second:
                agree_n += 1
                agree += actionable(ev, second[ev["id"]]) == pred
            rows.append((ev["id"], lab["actionable"], pred, a["pedestrian_impact"], a["basis"],
                         a["superseded_or_cleared"], a["evidence_quote"]))
        if pred and lab["actionable"]:
            tp += 1
        elif pred and not lab["actionable"]:
            fp += 1
            errors.append((ev["id"], "false positive", a["pedestrian_impact"], a["evidence_quote"], ev["comments"][:200]))
        elif not pred and lab["actionable"]:
            fn += 1
            errors.append((ev["id"], "false negative", a["pedestrian_impact"], a["evidence_quote"], ev["comments"][:200]))
        else:
            tn += 1
    n = tp + fp + fn + tn
    cost = tok_in / 1e6 * PRICE_IN + tok_out / 1e6 * PRICE_OUT
    prec = tp / (tp + fp) if tp + fp else float("nan")
    rec = tp / (tp + fn) if tp + fn else float("nan")

    L = ["# Agent judgment evaluation", "",
         f"Generated by `python scripts/eval_agent.py` on {now.strftime('%d %b %Y %H:%M UTC')} with `{MODEL}`.", "",
         f"**Records:** {meta['captured_records']} real records captured from the live TfL feed "
         f"({meta['capture_fetched_at'][:16]} UTC, all of London) + {meta['synthetic_records']} synthetic replay records. "
         f"{len(failures)} model calls failed.", "",
         "**Scored decision:** is the record *actionable*: an explicit pedestrian effect, with a verbatim quote "
         "that passes the evidence check, not superseded by its own update? This is the judgment that can "
         "change a published route. Labels are in `data/fixtures/eval_labels.json` (hand-labelled from the "
         "record text; see the limits below).", "",
         "| | labelled actionable | labelled not actionable |", "|---|---:|---:|",
         f"| **agent: actionable** | {tp} | {fp} |", f"| **agent: not actionable** | {fn} | {tn} |", "",
         f"- Accuracy {((tp + tn) / n):.1%} ({tp + tn}/{n}), precision {prec:.0%}, recall {rec:.0%}.",
         f"- Evidence check: {quotes_ok}/{quotes_checked} quotes offered for a pedestrian effect were found verbatim in the source and mention pedestrians.",
         f"- Impact class matched the label on {impact_ok}/{impact_n} labelled records.",
         f"- Run-to-run agreement on the actionable decision: {agree}/{agree_n} labelled records gave the same answer on a second pass.",
         f"- Latency per record: median {statistics.median(lat):.1f} s, max {max(lat):.1f} s. All {n} records in {wall:.0f} s with 8 parallel calls.",
         f"- Tokens: {tok_in:,} in, {tok_out:,} out, about ${cost:.2f} at list price (${cost / n * 1000:.1f} per 1,000 records). "
         "In production only in-area records that are new or modified are assessed, typically 0 to 5 per run.", "",
         "## Labelled records", "",
         "| record | label | agent | impact | basis | superseded | quote |", "|---|---|---|---|---|---|---|"]
    for rid, lab, pred, impact, basis, sup, quote in sorted(rows):
        mark = "" if lab == pred else " **(mismatch)**"
        L.append(f"| {rid} | {'actionable' if lab else 'not'} | {'actionable' if pred else 'not'}{mark} | {impact} | {basis} | "
                 f"{'yes' if sup else 'no'} | {quote.replace('|', '/')[:90]} |")
    L += ["", "## Mismatches", ""]
    if errors:
        for rid, kind, impact, quote, text in errors:
            L.append(f"- **{rid}** ({kind}): agent said `{impact}` quoting \"{quote}\". Text: {text}")
    else:
        L.append("None.")
    if failures:
        L += ["", "## Failed calls", ""] + [f"- {rid}: {err}" for rid, err in failures]
    L += ["", "## Limits of this evaluation", "",
          "- One snapshot of one feed on one afternoon. Only 8 of the 113 real records mention pedestrians at all, "
          "so recall is estimated from very few positives.",
          "- Labels were assigned by the same developer that built the system (the team's AI coding agent), "
          "without a second annotator, and they are not blind: several of the labelled records had already been "
          "run through the assessor during development. Treat the headline figure as a consistency check, not "
          "an independent benchmark.",
          "- Unlisted records were labelled not actionable by keyword screen, so a pedestrian effect phrased "
          "without any of the screened words would be mislabelled.",
          "- This measures the judgment step only. Location matching, expiry and the baseline-journey gate are "
          "covered by the deterministic tests in `tests/`.", ""]
    out = ROOT / "docs" / "EVALUATION.md"
    out.write_text("\n".join(L), encoding="utf-8")
    (ROOT / "docs" / "evaluation.json").write_text(json.dumps({
        "n": n, "tp": tp, "fp": fp, "fn": fn, "tn": tn, "precision": prec, "recall": rec,
        "quotes_ok": quotes_ok, "quotes_checked": quotes_checked, "agreement": [agree, agree_n],
        "tokens_in": tok_in, "tokens_out": tok_out, "cost_usd": round(cost, 2),
        "median_latency_s": statistics.median(lat), "failures": len(failures)}, indent=1), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
