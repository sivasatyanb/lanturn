"""Sensitivity analysis for the routing weights. Writes docs/SENSITIVITY.md.

Questions answered, over all 56 ordered pairs of the named places at a 22:30 departure:
  1. Trade-off curve: how much time does each unit of preference strength (lambda) buy?
  2. Weight robustness: if any one weight is halved or doubled, how often does the
     recommended route change, and by how much?
  3. Missing data: how much does the recommendation depend on what we assume about
     segments whose lighting is not recorded?
"""
from __future__ import annotations

import itertools
import json
import statistics
import sys
from dataclasses import replace
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from lantern.access import LONDON  # noqa: E402
from lantern.config import PLACES, ROOT  # noqa: E402
from lantern.cost import DEFAULT_WEIGHTS, FEATURES  # noqa: E402
from lantern.graph import load_graph  # noqa: E402
from lantern.routing import features_for, route_pair  # noqa: E402

from datetime import datetime  # noqa: E402

WHEN = datetime(2026, 11, 14, 22, 30, tzinfo=LONDON)
g = load_graph()
PAIRS = [(a, b) for a, b in itertools.permutations(PLACES, 2)]
LEN = {e["id"]: e["len"] for e in g.edges}


def solve(lam=1.0, weights=DEFAULT_WEIGHTS, prior=None):
    out = {}
    for a, b in PAIRS:
        pa, pb = PLACES[a], PLACES[b]
        out[(a, b)] = route_pair(g, (pa["lon"], pa["lat"]), (pb["lon"], pb["lat"]), WHEN,
                                 lam=lam, weights=weights, unknown_prior=prior)
    return out


CORRIDOR_M = 30.0   # two routes share a corridor where they run within 30 m of each other


def _line(route):
    from shapely.geometry import MultiLineString

    from lantern.geo import to_xy
    return MultiLineString([[to_xy(*c) for c in seg["coords"]] for seg in route["segments"]])


def overlap(r1, r2) -> float:
    """Corridor overlap: share of each route's length within 30 m of the other (symmetric mean).

    Edge-set overlap would treat the two pavements of one street as different routes;
    this measures whether the recommendation takes you along the same streets.
    """
    a, b = _line(r1), _line(r2)
    in_b = a.intersection(b.buffer(CORRIDOR_M)).length / a.length
    in_a = b.intersection(a.buffer(CORRIDOR_M)).length / b.length
    return (in_a + in_b) / 2


def compare(base, other):
    ov = [overlap(base[k]["preferred"], other[k]["preferred"]) for k in base]
    same = [o >= 0.9 for o in ov]
    dt = [abs(other[k]["preferred"]["time_s"] - base[k]["preferred"]["time_s"]) for k in base]
    return {"unchanged": sum(same) / len(same), "overlap": statistics.mean(ov),
            "min_overlap": min(ov), "mean_abs_dt_s": statistics.mean(dt), "max_abs_dt_s": max(dt)}


def main():
    base = solve()
    lines = ["# Sensitivity analysis", "",
             f"Generated by `python scripts/sensitivity.py`. {len(PAIRS)} journeys (all ordered pairs of the "
             f"{len(PLACES)} named places), departure 22:30 on 14 Nov 2026 (Kensington Gardens closed, "
             "Hyde Park open). No overlay applied.", ""]

    # 1. trade-off curve
    lines += ["## 1. What preference strength buys", "",
              "`lambda` scales all condition weights together. `lambda = 0` is the fastest route.", "",
              "| lambda | mean extra time | max extra time | mean time unlit (obs. or expected) | mean time off-street | mean share recorded lit | routes differing from fastest |",
              "|---:|---:|---:|---:|---:|---:|---:|"]
    curve = []
    for lam in (0.0, 0.25, 0.5, 1.0, 2.0, 4.0):
        sol = solve(lam=lam)
        extra = [sol[k]["preferred"]["time_s"] - sol[k]["fastest"]["time_s"] for k in sol]
        rel = [e / sol[k]["fastest"]["time_s"] for e, k in zip(extra, sol)]
        unlit = statistics.mean(sol[k]["preferred"]["exposure_s"]["unlit"] for k in sol)
        iso = statistics.mean(sol[k]["preferred"]["exposure_s"]["isolated"] for k in sol)
        lit = statistics.mean(sol[k]["preferred"]["lighting_share"]["yes"] for k in sol)
        diff = sum(not sol[k]["identical"] for k in sol) / len(sol)
        curve.append({"lam": lam, "mean_extra_s": statistics.mean(extra), "mean_extra_rel": statistics.mean(rel),
                      "max_extra_s": max(extra), "unlit_s": unlit, "isolated_s": iso, "lit_share": lit, "differs": diff})
        lines.append(f"| {lam:g} | {statistics.mean(extra):.0f} s ({statistics.mean(rel):.1%}) | {max(extra) / 60:.1f} min | "
                     f"{unlit:.0f} s | {iso:.0f} s | {lit:.1%} | {diff:.0%} |")
    c0, c1 = curve[0], next(c for c in curve if c["lam"] == 1.0)
    c4 = curve[-1]
    lines += ["",
              f"Reading: at the default `lambda = 1` the average journey is {c1['mean_extra_s']:.0f} s "
              f"({c1['mean_extra_rel']:.1%}) longer than the fastest route and spends "
              f"{1 - c1['unlit_s'] / c0['unlit_s']:.0%} less time on segments that are unlit or expected to be, and "
              f"{1 - c1['isolated_s'] / c0['isolated_s']:.0%} less time away from any street. Quadrupling the "
              f"preference to `lambda = 4` adds a further {c4['mean_extra_s'] - c1['mean_extra_s']:.0f} s on average for "
              f"a further {(c1['unlit_s'] - c4['unlit_s']) / c0['unlit_s']:.0%} of the original unlit time: most of "
              "the available improvement is already taken at the default.", ""]

    # 2. one-at-a-time weights
    lines += ["## 2. Robustness to each weight", "",
              "Each weight is halved and doubled in turn with the others held at their defaults. "
              "\"Overlap\" is corridor overlap with the default recommendation: the share of route length "
              "running within 30 m of the other route, so walking on the opposite pavement of the same street "
              "counts as the same route. \"Same corridor\" is the share of journeys with overlap of at least 90%.", "",
              "| weight | default | scaled | same corridor | mean overlap | worst overlap | mean abs. time change |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    robust = []
    for k in FEATURES:
        for f in (0.5, 2.0):
            w = replace(DEFAULT_WEIGHTS, **{k: getattr(DEFAULT_WEIGHTS, k) * f})
            c = compare(base, solve(weights=w))
            robust.append({"weight": k, "factor": f, **c})
            lines.append(f"| {k} | {getattr(DEFAULT_WEIGHTS, k):g} | x{f:g} | {c['unchanged']:.0%} | "
                         f"{c['overlap']:.1%} | {c['min_overlap']:.0%} | {c['mean_abs_dt_s']:.0f} s |")
    worst = min(robust, key=lambda r: r["overlap"])
    mean_same = statistics.mean(r["unchanged"] for r in robust)
    lines += ["",
              f"Reading: averaged over the eight perturbations, {mean_same:.0%} of journeys keep the same "
              f"corridor. The recommendation is least stable under `{worst['weight']}` x{worst['factor']:g} "
              f"({worst['unchanged']:.0%} same corridor, {worst['overlap']:.0%} mean overlap, worst single journey "
              f"{worst['min_overlap']:.0%}). Time differences stay small (largest mean change "
              f"{max(r['mean_abs_dt_s'] for r in robust):.0f} s) because the alternatives are near-ties in walking "
              "time: a 2x error in any single weight moves some journeys onto a parallel street, but does not "
              "produce long detours.", ""]

    # 3. unknown lighting
    feat = features_for(g)
    lines += ["## 3. Dependence on unrecorded lighting", "",
              "Lighting is recorded on " + f"{1 - g.meta['lighting_coverage_by_length']['unknown']:.0%}"
              " of network length. For the rest we use P(unlit | street group) estimated from recorded "
              "segments in the same area:", "",
              "| street group | P(unlit) used | recorded km | unrecorded km | coverage |", "|---|---:|---:|---:|---:|"]
    for grp, v in feat.priors.items():
        if grp.startswith("_"):
            continue
        lines.append(f"| {grp} | {v['p_unlit']:.3f} | {v['observed_km']} | {v['unknown_km']} | {v['coverage']:.0%} |")
    lines += ["", "Rerunning with every unrecorded segment assumed lit (0) and assumed unlit (1):", "",
              "| assumption for unrecorded segments | same corridor | mean overlap | worst overlap | mean abs. time change | mean share of route unrecorded |",
              "|---|---:|---:|---:|---:|---:|"]
    missing = []
    for label, prior in (("all lit (0)", 0.0), ("group estimate (default)", None), ("all unlit (1)", 1.0)):
        sol = base if prior is None else solve(prior=prior)
        c = compare(base, sol)
        unk = statistics.mean(sol[k]["preferred"]["lighting_share"]["unknown"] for k in sol)
        missing.append({"assumption": label, **c, "unknown_share": unk})
        lines.append(f"| {label} | {c['unchanged']:.0%} | {c['overlap']:.1%} | {c['min_overlap']:.0%} | "
                     f"{c['mean_abs_dt_s']:.0f} s | {unk:.1%} |")
    opt, pess = missing[0], missing[-1]
    lines += ["",
              f"Reading: this is the largest source of uncertainty in the model. Assuming every unrecorded "
              f"segment is unlit keeps {pess['unchanged']:.0%} of journeys in the same corridor (mean overlap "
              f"{pess['overlap']:.0%}) and costs {pess['mean_abs_dt_s']:.0f} s on average; the routes that move "
              f"go onto streets with recorded lighting (unrecorded share falls from "
              f"{missing[1]['unknown_share']:.1%} to {pess['unknown_share']:.1%}). Assuming they are all lit keeps "
              f"{opt['unchanged']:.0%}. We therefore never present unrecorded lighting as lit: the app shows the "
              "unrecorded share of every route next to the lit share.", ""]

    out = ROOT / "docs" / "SENSITIVITY.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    (ROOT / "docs" / "sensitivity.json").write_text(
        json.dumps({"curve": curve, "weights": robust, "missing": missing}, indent=1), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
