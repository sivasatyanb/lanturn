"""Generate web/tokens.css from design/figma-tokens.json (exported from the Figma file).

  python scripts/build_tokens.py

Colours, radii, spacing and type styles in the app all come from this file, so a change to
a Figma variable reaches the app by re-exporting the JSON and rerunning this script.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEIGHT = {"Regular": 400, "Italic": 400, "Medium": 500, "Semi Bold": 600, "Bold": 700, "Extra Bold": 800}


def main() -> int:
    src = json.loads((ROOT / "design" / "figma-tokens.json").read_text(encoding="utf-8"))
    out = ["/* GENERATED by scripts/build_tokens.py from design/figma-tokens.json. Do not edit.",
           f"   Source: Figma variable collection '{src['collection']}' (mode '{src['mode']}')",
           f"   {src['figma_file']} */", ":root {"]
    for name, css, kind, value in src["variables"]:
        unit = "px" if kind == "FLOAT" else ""
        out.append(f"  {css}: {value}{unit};{' ' * max(1, 30 - len(css) - len(value) - len(unit))}/* {name} */")
    out.append("")
    out.append("  /* text styles: font shorthand = style weight size/line-height family */")
    out.append('  --font-family: "Inter", -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;')
    for name, family, style, size, lh, ls in src["text_styles"]:
        var = "--type-" + name.lower().replace("/", "-")
        italic = "italic " if style == "Italic" else ""
        out.append(f"  {var}: {italic}{WEIGHT[style]} {size:g}px/{lh:g}px var(--font-family);   /* {name} */")
        if ls:
            out.append(f"  {var}-tracking: {ls:g}px;")
    out.append("}")
    path = ROOT / "web" / "tokens.css"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(src['variables'])} variables, {len(src['text_styles'])} text styles)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
